namespace CitOmni\Mcp\Support\OAuth;

use League\OAuth2\Server\Entities\RefreshTokenEntityInterface;
use League\OAuth2\Server\Entities\Traits\EntityTrait;
use League\OAuth2\Server\Entities\Traits\RefreshTokenTrait;

/** League owns refresh-token encryption; the repository enforces rotation. */
final class RefreshToken implements RefreshTokenEntityInterface {
	use EntityTrait;
	use RefreshTokenTrait;

	/**
	 * Bind each opaque identifier to its grant family before League encrypts it.
	 *
	 * @param string $family Server-generated authorization code identifier.
	 */
	public function __construct(private readonly string $family) {
	}

	/**
	 * Keep the random component generated by League and prepend the family ID.
	 *
	 * @param string $identifier Cryptographically random identifier from League.
	 * @return void
	 */
	public function setIdentifier(string $identifier): void {
		$this->identifier = $this->family . '.' . $identifier;
	}
}
